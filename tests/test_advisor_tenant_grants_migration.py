def migration():
    spec = importlib.util.spec_from_file_location('grant_revision', ROOT /
        'migrations/versions/20261018_0109_advisor_tenant_grants.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_single_head_and_offline_upgrade_sql():
    output = io.StringIO()
    config = Config(str(ROOT / 'alembic.ini'), stdout=output, output_buffer=output)
    assert ScriptDirectory.from_config(config).get_heads() == [REVISION]
    assert migration().down_revision == '0108_advisor_account_links'
    command.upgrade(config, '0108_advisor_account_links:' + REVISION, sql=True)
    sql = output.getvalue()
    assert sql.count('CREATE TABLE advisor_tenant_grants') == 1
    for required in ['GENERATED BY DEFAULT AS IDENTITY', 'ON DELETE RESTRICT',
        'uq_advisor_tenant_grants_active', 'WHERE revoked_at IS NULL',
        'OLD.revoked_at IS NOT NULL', 'NEW.id', 'NEW.grant_source',
        'REVOKE ALL ON TABLE advisor_tenant_grants FROM PUBLIC',
        'REVOKE ALL ON TABLE advisor_tenant_grants FROM sem_runtime',
        'GRANT SELECT, INSERT, UPDATE ON TABLE advisor_tenant_grants TO sem_runtime',
        'pg_get_serial_sequence', 'REVOKE ALL ON SEQUENCE', 'RAISE NOTICE']:
        assert required in sql
    assert 'GRANT DELETE' not in sql and 'GRANT USAGE' not in sql
    assert 'ALTER DEFAULT PRIVILEGES' not in sql
    assert 'CREATE ROLE' not in sql
    assert 'INSERT INTO advisor_tenant_grants' not in sql  # Independently approved import.
    with pytest.raises(RuntimeError, match='cannot be downgraded'):
        migration().downgrade()


def test_frozen_backfill_never_restores_managed_users():
    sql = BACKFILL.read_text(encoding='utf-8')
    assert 'WHERE g.user_id = e.user_id' in sql
    assert 'WHERE g.user_id = e.user_id AND' not in sql
    assert "ON CONFLICT (user_id, tenant_id) WHERE revoked_at IS NULL DO NOTHING" in sql
    assert 'invalid role permissions' in sql
    assert 'u.is_active' not in sql and 'u.locked_until' not in sql


@pytest.mark.skipif(not os.getenv('SEO_MIGRATION_TEST_DATABASE_URL'), reason='requires disposable loopback PG fixture')
def test_native_pg_constraints_irreversible_history_backfill_and_exact_acl():
    url = make_url(os.environ['SEO_MIGRATION_TEST_DATABASE_URL'])
    if url.host not in ('localhost', '127.0.0.1', '::1') or url.database != 'test' or url.query:
        raise ValueError('Only disposable loopback test database is permitted')

    async def scenario():
        schema = 'advisor_test_' + uuid4().hex
        engine = create_async_engine(url, connect_args={'server_settings':{
            'search_path':schema, 'statement_timeout':'15000', 'lock_timeout':'5000'}})
        role_created = False
        try:
            async with engine.begin() as conn:
                # This fixture owns an ephemeral CI container, never a live DB.
                assert await conn.scalar(text("SELECT rolsuper FROM pg_roles WHERE rolname=current_user"))
                if await conn.scalar(text("SELECT 1 FROM pg_roles WHERE rolname='sem_runtime'")):
                    raise ValueError('Fixture requires absent sem_runtime to avoid touching an existing role')
                await conn.execute(text('CREATE ROLE sem_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE'))
                role_created = True
                await conn.execute(text(f'CREATE SCHEMA "{schema}"'))
                await conn.execute(text(f'GRANT USAGE ON SCHEMA "{schema}" TO sem_runtime'))
                await conn.execute(text('CREATE TABLE users (id bigint PRIMARY KEY, role_id bigint, tenant_id bigint, is_active boolean, locked_until timestamp)'))
                await conn.execute(text('CREATE TABLE tenants (id bigint PRIMARY KEY)'))
                await conn.execute(text('CREATE TABLE roles (id bigint PRIMARY KEY, name text, is_system boolean, permissions jsonb)'))
                await conn.execute(text('INSERT INTO tenants VALUES (1),(2),(3)'))
                await conn.execute(text('INSERT INTO users VALUES (99,99,NULL,true,NULL)'))
                # Deliberately hostile fixture defaults: migration must revoke these.
                await conn.execute(text(f'ALTER DEFAULT PRIVILEGES IN SCHEMA "{schema}" GRANT ALL ON TABLES TO sem_runtime'))
                await conn.execute(text(f'ALTER DEFAULT PRIVILEGES IN SCHEMA "{schema}" GRANT ALL ON SEQUENCES TO sem_runtime'))
                audit_sql = AUDIT.read_text(encoding='utf-8')
                snapshot_sql = audit_sql.split('-- SNAPSHOT-BEGIN',1)[1].split('-- SNAPSHOT-END',1)[0]
                before = list(await conn.execute(text(snapshot_sql)))
                def upgrade(sync):
                    with Operations.context(MigrationContext.configure(sync)):
                        migration().upgrade()
                await conn.run_sync(upgrade)
                after = list(await conn.execute(text(snapshot_sql)))
                assert before == after
                privileges_sql = audit_sql.split('-- TABLE-BEGIN',1)[1].split('-- TABLE-END',1)[0]
                # Audit template is schema-neutral for owned test schemas.
                privileges = dict((await conn.execute(text(privileges_sql.replace('public.advisor_tenant_grants', schema+'.advisor_tenant_grants')))).all())
                assert privileges == {p:p in ('SELECT','INSERT','UPDATE') for p in
                                      ['SELECT','INSERT','UPDATE','DELETE','TRUNCATE','REFERENCES','TRIGGER']}
                assert await conn.scalar(text("SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid='advisor_tenant_grants'::regclass")) != 'sem_runtime'
                sequence_name = await conn.scalar(text("SELECT pg_get_serial_sequence('advisor_tenant_grants','id')"))
                for privilege in ('USAGE','SELECT','UPDATE'):
                    assert not await conn.scalar(text('SELECT has_sequence_privilege(:role,:seq,:p)'),
                        {'role':'sem_runtime','seq':sequence_name,'p':privilege})
                assert not await conn.scalar(text("SELECT has_function_privilege('sem_runtime','advisor_tenant_grants_protect_history()','EXECUTE')"))
                roles = [
                    ('seo',False,{'seo.site':'edit','seo.content':'edit'}),
                    ('geo',False,{'geo.assets':'edit','geo.content':'edit'}),
                    ('管理员',True,{'seo.site':'edit','seo.content':'edit'}),
                    ('settings',False,{'geo.assets':'edit','geo.content':'edit','settings.accounts':'edit'}),
                    ('customer',False,{'seo.site':'view','seo.content':'view'}),
                    ('seo-half',False,{'seo.site':'edit'}),
                    ('dirty-settings',False,{'seo.site':'edit','seo.content':'edit','settings.future':'edit'}),
                    ('noisy-seo',False,{'seo.site':'edit','seo.content':'edit','unknown':{'nested':True}}),
                ]
                expected=[]
                for i,(name,system,perms) in enumerate(roles,1):
                    await conn.execute(text('INSERT INTO roles VALUES (:id,:name,:system,CAST(:p AS jsonb))'),
                        {'id':i,'name':name,'system':system,'p':json.dumps(perms)})
                    await conn.execute(text('INSERT INTO users VALUES (:id,:id,1,false,CURRENT_TIMESTAMP)'),{'id':i})
                    if is_advisor_role(SimpleNamespace(name=name,is_system=system,permissions=perms)):
                        expected.append(i)
                await conn.execute(text('INSERT INTO users VALUES (20,1,NULL,true,NULL),(21,1,999,true,NULL)'))
                backfill = BACKFILL.read_text(encoding='utf-8')
                # asyncpg uses one statement per execute; retain DO as one block.
                preflight = backfill[backfill.index('DO $$'):backfill.index('WITH eligible')]
                insert_sql = backfill[backfill.index('WITH eligible'):backfill.index('\nCOMMIT;')]
                await conn.execute(text(preflight))
                await conn.execute(text(insert_sql))
                assert list(await conn.scalars(text('SELECT user_id FROM advisor_tenant_grants ORDER BY user_id'))) == expected
                assert expected == [1,2,8]
                assert (await conn.execute(text(insert_sql))).rowcount == 0
                for statement in [
                    "INSERT INTO advisor_tenant_grants(user_id,tenant_id,granted_by,grant_source) VALUES (1,1,99,'admin')",
                    "INSERT INTO advisor_tenant_grants(user_id,tenant_id,grant_source) VALUES (7,1,'admin')",
                    "INSERT INTO advisor_tenant_grants(user_id,tenant_id,granted_by,grant_source) VALUES (7,1,99,'backfill')",
                    "INSERT INTO advisor_tenant_grants(user_id,tenant_id,granted_by,grant_source) VALUES (7,999,99,'admin')",
                ]:
                    with pytest.raises(Exception):
                        async with conn.begin_nested():
                            await conn.execute(text(statement))
                original = await conn.scalar(text('SELECT id FROM advisor_tenant_grants WHERE user_id=1'))
                # Test as runtime: identity default INSERT needs no sequence grants.
                await conn.execute(text('SET LOCAL ROLE sem_runtime'))
                new_id = await conn.scalar(text("INSERT INTO advisor_tenant_grants(user_id,tenant_id,granted_by,grant_source) VALUES (1,2,99,'admin') RETURNING id"))
                for column,value in [('id','id+100'),('user_id','2'),('tenant_id','3'),
                    ('granted_by','1'),('grant_source',"'backfill'"),('granted_at',"granted_at + interval '1 second'")]:
                    with pytest.raises(Exception):
                        async with conn.begin_nested():
                            await conn.execute(text(f'UPDATE advisor_tenant_grants SET {column}={value} WHERE id=:id'),{'id':new_id})
                await conn.execute(text("UPDATE advisor_tenant_grants SET revoked_at=now(),revoked_by=99,revoke_reason='admin_uncheck' WHERE id=:id"),{'id':original})
                for update in ['revoked_at=NULL,revoked_by=NULL,revoke_reason=NULL',"revoke_reason='changed'",'id=id']:
                    with pytest.raises(Exception):
                        async with conn.begin_nested():
                            await conn.execute(text('UPDATE advisor_tenant_grants SET '+update+' WHERE id=:id'),{'id':original})
                for forbidden in ['DELETE FROM advisor_tenant_grants', 'TRUNCATE advisor_tenant_grants']:
                    with pytest.raises(Exception):
                        async with conn.begin_nested():
                            await conn.execute(text(forbidden))
                await conn.execute(text('RESET ROLE'))
                assert (await conn.execute(text(insert_sql))).rowcount == 0  # History prevents backfill resurrection.
                await conn.execute(text('SET LOCAL ROLE sem_runtime'))
                regrant = await conn.scalar(text("INSERT INTO advisor_tenant_grants(user_id,tenant_id,granted_by,grant_source) VALUES (1,1,99,'admin') RETURNING id"))
                assert regrant != original
                await conn.execute(text('RESET ROLE'))
                await conn.execute(text("INSERT INTO roles VALUES (100,'invalid',false,'[]'::jsonb)"))
                with pytest.raises(Exception):
                    async with conn.begin_nested():
                        await conn.execute(text(preflight))
        finally:
            async with engine.begin() as conn:
                await conn.execute(text(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE'))
                if role_created:
                    await conn.execute(text('DROP ROLE IF EXISTS sem_runtime'))
            await engine.dispose()
    asyncio.run(scenario())
