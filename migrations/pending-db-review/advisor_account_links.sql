CREATE TABLE advisor_account_links (
    user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    group_id uuid NOT NULL,
    tenant_id bigint NOT NULL,
    created_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_advisor_account_links_group_id ON advisor_account_links(group_id);

CREATE TABLE advisor_account_switch_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_user_id bigint NOT NULL,
    to_user_id bigint NOT NULL,
    action varchar(16) NOT NULL CONSTRAINT ck_advisor_account_audit_action
        CHECK (action IN ('link', 'unlink', 'switch')),
    actor_user_id bigint NOT NULL,
    group_id uuid,
    status varchar(16) NOT NULL CONSTRAINT ck_advisor_account_audit_status
        CHECK (status IN ('success', 'denied')),
    reason varchar(80),
    ip_address varchar(45),
    user_agent varchar(512),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_advisor_account_switch_audit_from_user_id
    ON advisor_account_switch_audit(from_user_id, created_at);

